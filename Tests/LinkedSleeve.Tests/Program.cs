using Autodesk.Revit.DB;
using Autodesk.Revit.DB.Plumbing;
using YD_RevitTools.LicenseManager.Commands.MEP;

int checks=0;
void Check(bool value,string message){if(!value)throw new Exception(message);checks++;}
void Reject(Action action,string message){try{action();}catch(InvalidOperationException){Check(true,message);return;}throw new Exception(message);}
Pipe PipeIn(Document doc,long id)=>doc.Add(new Pipe { Id=new ElementId(id), Location=new LocationCurve { Curve=new Curve(new XYZ(0,0,1),new XYZ(2,0,1.1)) } });
var model=new Document();var linked=new Document();var other=new Document();
var localPipe=PipeIn(model,42);var linkPipe=PipeIn(linked,42);var otherPipe=PipeIn(other,42);
var first=model.Add(new RevitLinkInstance{Id=new ElementId(101),Linked=linked,Name="MEP-A"});
var second=model.Add(new RevitLinkInstance{Id=new ElementId(102),Linked=linked,Name="MEP-B"});
var third=model.Add(new RevitLinkInstance{Id=new ElementId(103),Linked=other});
first.Transform=new Transform{X=new XYZ(0,1,0),Y=new XYZ(-1,0,0),Origin=new XYZ(100,200,3)};
var local=new SleevePipeSource(localPipe);var a=new SleevePipeSource(linkPipe,first);var b=new SleevePipeSource(linkPipe,second);var c=new SleevePipeSource(otherPipe,third);
Check(new[]{local.Key,a.Key,b.Key,c.Key}.Distinct().Count()==4,"same numeric IDs and repeated link instances stay distinct");
Check(a.ModelCurve.GetEndPoint(0).DistanceTo(new XYZ(100,200,4))<1e-9,"translated and rotated start is in host coordinates");
Check(a.ModelCurve.GetEndPoint(1).DistanceTo(new XYZ(100,202,4.1))<1e-9,"rotation retains source slope");
Check(((LocationCurve)linkPipe.Location).Curve.GetEndPoint(0).DistanceTo(new XYZ(0,0,1))<1e-9,"source geometry remains unchanged");
second.Transform=new Transform{X=new XYZ(-1,0,0),Origin=new XYZ(20,0,0)};
Check(b.ModelCurve.GetEndPoint(1).DistanceTo(new XYZ(18,0,1.1))<1e-9,"mirrored instance transform is applied");
var sources=SleevePipeSource.For(model,new List<Element>{linkPipe},new PipeSleeveOptions{PipeSources=new List<SleevePipeSource>{a,b,a}});
Check(sources.Count==2,"deduplicate selection within one instance only");
Reject(()=>SleevePipeSource.For(model,new List<Element>{linkPipe},new PipeSleeveOptions()),"foreign elements without link context are rejected");
Reject(()=>new SleevePipeSource(otherPipe,first),"mismatched link document is rejected");
var host=model.Add(new Element());var sleeve=model.Add(new FamilyInstance());
sleeve.Parameters["來源管線Id"]=new Parameter{Text="42"};
Check(SleeveSourceRecord.Matches(sleeve,local),"legacy local source is retained");
Check(!SleeveSourceRecord.Matches(sleeve,a),"legacy local source cannot match a colliding linked ID");
var candidate=new PipeSleeveCandidate{Source=a,Pipe=linkPipe,HostElement=host};
SleeveSourceRecord.Save(sleeve,candidate);
Check(SleeveSourceRecord.HasRecord(sleeve),"source record does not depend on family parameter schema");
Check(SleeveSourceRecord.Matches(sleeve,a)&&!SleeveSourceRecord.Matches(sleeve,b)&&!SleeveSourceRecord.Matches(sleeve,local),"persisted source is specific to link instance and unique element");
Check(SleeveSourceRecord.Resolve(model,sleeve,out _)?.Key==a.Key,"roundtrip resolves linked source");
Check(SleeveSourceRecord.MatchesHost(sleeve,candidate)==true,"host identity roundtrip");
candidate.HostLinkUniqueId=second.UniqueId;
Check(SleeveSourceRecord.MatchesHost(sleeve,candidate)==false,"host link instance is part of matching");
candidate.HostLinkUniqueId=null;
first.Transform.Origin=new XYZ(101,202,5);
Check(SleeveSourceRecord.Resolve(model,sleeve,out _).ModelCurve.GetEndPoint(0).DistanceTo(new XYZ(101,202,6))<1e-9,"recheck uses current link placement");
first.Linked=null;
Check(SleeveSourceRecord.Resolve(model,sleeve,out var unloaded)==null&&unloaded.Contains("尚未載入"),"unloaded link is explicit and never falls back to local ID");
first.Linked=linked;
Check(SleeveSourceRecord.Resolve(model,sleeve,out _)?.Key==a.Key,"reload restores source resolution");
model.Elements.Remove(first);
Check(SleeveSourceRecord.Resolve(model,sleeve,out var removed)==null&&removed.Contains("移除"),"removed instance is not replaced by another instance of same file");
model.Add(first);linked.Elements.Remove(linkPipe);PipeIn(linked,42);
Check(SleeveSourceRecord.Resolve(model,sleeve,out var missing)==null&&missing.Contains("刪除"),"reused element ID cannot replace recorded source unique ID");
linked.Add(linkPipe);
first.Linked=other;
Check(SleeveSourceRecord.Resolve(model,sleeve,out _)==null,"retargeted link cannot silently map to same ID in another document");
first.Linked=linked;
var noParameter=model.Add(new FamilyInstance());SleeveSourceRecord.Save(noParameter,candidate);
Check(SleeveSourceRecord.Resolve(model,noParameter,out _)?.Key==a.Key,"tracking works even without a source-ID family parameter");
Console.WriteLine($"PASS {checks} linked sleeve source checks (API doubles; no native solid/transaction validation).");
